-- =========================================================
-- TABLA: ROL
-- =========================================================
CREATE TABLE ROL (
    ID_ROL      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE      VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

-- =========================================================
-- TABLA: USUARIO
-- =========================================================
CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ROL          NUMBER          NOT NULL,
    NOMBRE          VARCHAR2(20)    NOT NULL,
    APELLIDO        VARCHAR2(20)    NOT NULL,
    USERNAME        VARCHAR2(20)    NOT NULL,
    CORREO          VARCHAR2(30)    NOT NULL,
    CLAVE           VARCHAR2(30)    NOT NULL,
    ESTADO          CHAR(1)         DEFAULT 'A' NOT NULL,
    FECHA_CREACION  DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL)
        REFERENCES ROL (ID_ROL),
    CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('A', 'I')) -- Activo/Inactivo
);

-- =========================================================
-- TABLA: MESA
-- =========================================================
CREATE TABLE MESA (
    ID_MESA         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_MESA     NUMBER         NOT NULL,
    CAPACIDAD       NUMBER         NOT NULL,
    ESTADO          VARCHAR2(20)   DEFAULT 'LIBRE' NOT NULL,
    CONSTRAINT PK_MESA PRIMARY KEY (ID_MESA),
    CONSTRAINT UQ_MESA_NUMERO UNIQUE (NUMERO_MESA),
    CONSTRAINT CK_MESA_CAPACIDAD CHECK (CAPACIDAD > 0),
    CONSTRAINT CK_MESA_ESTADO CHECK (ESTADO IN ('LIBRE', 'OCUPADA', 'INACTIVA'))
);

-- =========================================================
-- TABLA: CATEGORIA_PRODUCTO
-- =========================================================
CREATE TABLE CATEGORIA_PRODUCTO (
    ID_CATEGORIA   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE         VARCHAR2(20)   NOT NULL,
    CONSTRAINT PK_CATEGORIA_PRODUCTO PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UQ_CATEGORIA_PRODUCTO_NOMBRE UNIQUE (NOMBRE)
);

-- =========================================================
-- TABLA: PRODUCTO
-- =========================================================
CREATE TABLE PRODUCTO (
    ID_PRODUCTO     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CATEGORIA    NUMBER         NOT NULL,
    NOMBRE          VARCHAR2(30)  NOT NULL,
    DESCRIPCION     VARCHAR2(250),
    PRECIO          NUMBER(10,2)   NOT NULL,
    DISPONIBLE      CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES CATEGORIA_PRODUCTO (ID_CATEGORIA),
    CONSTRAINT UQ_PRODUCTO_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_PRODUCTO_DISPONIBLE CHECK (DISPONIBLE IN ('S', 'N'))
);

-- =========================================================
-- TABLA: PEDIDO
-- =========================================================
CREATE TABLE PEDIDO (
    ID_PEDIDO              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_PEDIDO          VARCHAR2(20)    NOT NULL,
    ID_MESA                NUMBER          NOT NULL,
    ID_USUARIO_MESERO      NUMBER          NOT NULL,
    FECHA_HORA_CREACION    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO                 VARCHAR2(20)    DEFAULT 'PENDIENTE' NOT NULL,
    TOTAL                  NUMBER(10,2)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PEDIDO PRIMARY KEY (ID_PEDIDO),
    CONSTRAINT FK_PEDIDO_MESA FOREIGN KEY (ID_MESA)
        REFERENCES MESA (ID_MESA),
    CONSTRAINT FK_PEDIDO_USUARIO_MESERO FOREIGN KEY (ID_USUARIO_MESERO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT UQ_PEDIDO_NUMERO UNIQUE (NUMERO_PEDIDO),
    CONSTRAINT CK_PEDIDO_TOTAL CHECK (TOTAL >= 0),
    CONSTRAINT CK_PEDIDO_ESTADO CHECK (
        ESTADO IN (
            'PENDIENTE',
            'EN_PREPARACION',
            'LISTO',
            'ENTREGADO',
            'FACTURADO',
            'CANCELADO'
        )
    )
);

-- =========================================================
-- TABLA: DETALLE_PEDIDO
-- =========================================================
CREATE TABLE DETALLE_PEDIDO (
    ID_DETALLE_PEDIDO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PEDIDO           NUMBER         NOT NULL,
    ID_PRODUCTO         NUMBER         NOT NULL,
    CANTIDAD            NUMBER         NOT NULL,
    PRECIO_UNITARIO     NUMBER(10,2)   NOT NULL,
    SUBTOTAL            NUMBER(10,2)   NOT NULL,
    OBSERVACION_ITEM    VARCHAR2(250),
    CONSTRAINT PK_DETALLE_PEDIDO PRIMARY KEY (ID_DETALLE_PEDIDO),
    CONSTRAINT FK_DETALLE_PEDIDO_PEDIDO FOREIGN KEY (ID_PEDIDO)
        REFERENCES PEDIDO (ID_PEDIDO),
    CONSTRAINT FK_DETALLE_PEDIDO_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT CK_DETALLE_PEDIDO_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_PEDIDO_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_DETALLE_PEDIDO_SUBTOTAL CHECK (SUBTOTAL >= 0)
);

-- =========================================================
-- TABLA: FACTURA
-- =========================================================
CREATE TABLE FACTURA (
    ID_FACTURA             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_FACTURA         VARCHAR2(20)   NOT NULL,
    ID_PEDIDO              NUMBER         NOT NULL,
    ID_USUARIO_CAJERO      NUMBER         NOT NULL,
    FECHA_HORA_FACTURA     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    TOTAL                  NUMBER(10,2)   DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FACTURA PRIMARY KEY (ID_FACTURA),
    CONSTRAINT FK_FACTURA_PEDIDO FOREIGN KEY (ID_PEDIDO)
        REFERENCES PEDIDO (ID_PEDIDO),
    CONSTRAINT FK_FACTURA_USUARIO_CAJERO FOREIGN KEY (ID_USUARIO_CAJERO)
        REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT UQ_FACTURA_NUMERO UNIQUE (NUMERO_FACTURA),
    CONSTRAINT UQ_FACTURA_PEDIDO UNIQUE (ID_PEDIDO),
    CONSTRAINT CK_FACTURA_TOTAL CHECK (TOTAL >= 0)
);

